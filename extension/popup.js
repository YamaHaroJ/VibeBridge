function renderEnabled(value) {
  toggle.setAttribute("aria-checked", String(value));
  title.textContent = value ? "VibeBridge is on" : "VibeBridge is off";
  copy.textContent = value
    ? "Project context is added automatically."
    : "ChatGPT messages are sent without project context.";
}
function renderStatus(element, label, state, message) {
  element.dataset.state = state;
  label.textContent = message;
}
async function callAgent(path, token, timeoutMs = 8000) {
  const controller = new AbortController();
  const timeout = setTimeout(() => controller.abort(), timeoutMs);
  try {
    const response = await fetch("http://127.0.0.1:43127" + path, {
      headers: {Authorization: "Bearer " + token},
      signal: controller.signal
    });
    const data = await response.json();
    if (!response.ok) throw new Error(data.error || "Request failed");
    return data;
  } catch (error) {
    if (error.name === "AbortError") {
      throw new Error("VibeBridge local agent timed out. Check that the Mac agent is running, then retry.");
    }
    throw error;
  } finally {
    clearTimeout(timeout);
  }
}
async function requestBackgroundUpdate() {
  // A popup opening should never require the user to initiate an update manually.
  // Limit requests to once every 10 minutes to avoid spawning redundant updater processes.
  try {
    const saved = await chrome.storage.local.get(["token", "lastAutomaticUpdateRequest"]);
    if (!saved.token) return;
    const now = Date.now();
    if (saved.lastAutomaticUpdateRequest && now - saved.lastAutomaticUpdateRequest < 10 * 60 * 1000) return;
    await chrome.storage.local.set({lastAutomaticUpdateRequest: now});
    const response = await fetch("http://127.0.0.1:43127/update", {
      method: "POST",
      headers: {Authorization: "Bearer " + saved.token, "Content-Type": "application/json"},
      body: "{}"
    });
    if (!response.ok) {
      await chrome.storage.local.remove("lastAutomaticUpdateRequest");
    }
  } catch {
    // A failed attempt must not suppress retries for the next ten minutes.
    // Remove the throttle marker so the next popup open can retry immediately.
    try {
      await chrome.storage.local.remove("lastAutomaticUpdateRequest");
    } catch {
      // Storage can be unavailable during extension shutdown; the next open retries.
    }
  }
}

